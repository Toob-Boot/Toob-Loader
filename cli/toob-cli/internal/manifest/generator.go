func writeFileIfChanged(path string, data []byte) error {
	if old, err := os.ReadFile(path); err == nil && string(old) == string(data) {
		return nil
	}
	return os.WriteFile(path, data, 0o644)
}

func VerifyMacroUsage(headerPath, bootloaderDir, halChipDir string, extraDirs []string) error {
	ui.Step("Validating macro consumption in C code...")

	data, err := os.ReadFile(headerPath)
	if err != nil {
		return err
	}
	content := string(data)

	re := regexp.MustCompile(`#define\s+(CHIP_[A-Z0-9_]+|BOOT_[A-Z0-9_]+|TOOB_[A-Z0-9_]+)`)
	matches := re.FindAllStringSubmatch(content, -1)
	macros := make(map[string]bool)
	for _, m := range matches {
		if len(m) > 1 && m[1] != "GENERATED_BOOT_CONFIG_H" {
			macros[m[1]] = false // not used yet
		}
	}

	dirsToWalk := []string{bootloaderDir}
	if halChipDir != "" {
		dirsToWalk = append(dirsToWalk, halChipDir)
	}
	dirsToWalk = append(dirsToWalk, extraDirs...)

	var errAllFound = fmt.Errorf("all macros found")
	for _, dir := range dirsToWalk {
		walkErr := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
			if err != nil {
				return nil
			}
			if !d.IsDir() && (strings.HasSuffix(d.Name(), ".c") || strings.HasSuffix(d.Name(), ".h")) {
				b, err := os.ReadFile(path)
				if err == nil {
					text := string(b)
					allUsed := true
					for m, used := range macros {
						if !used {
							if strings.Contains(text, m) {
								macros[m] = true
							} else {
								allUsed = false
							}
						}
					}
					if allUsed {
						return errAllFound
					}
				}
			}
			return nil
		})
		if walkErr == errAllFound {
			break
		}
		if walkErr != nil {
			return walkErr
		}
	}

	var unreferenced []string
	for m, used := range macros {
		if !used {
			unreferenced = append(unreferenced, m)
		}
	}

	if len(unreferenced) > 0 {
		sort.Strings(unreferenced)
		var errb strings.Builder
		errb.WriteString("\n======================================================================\n")
		errb.WriteString("FATAL ERROR: MANIFEST COMPILER FAIL-FAST TRIGGERED!\n")
		errb.WriteString("The following macros were generated but NEVER referenced in the C code:\n")
		for _, m := range unreferenced {
			errb.WriteString(fmt.Sprintf("  - %s\n", m))
		}
		errb.WriteString("=\nThis indicates a severe architectural gap! Either:\n")
		errb.WriteString("  1. The C code is using a hardcoded fallback and ignoring the manifest.\n")
		errb.WriteString("  2. The manifest is generating dead code that should be pruned.\n")
		errb.WriteString("  3. You are developing/building locally and the registry sources in the cache (~/.toob/registry) are out of sync with your local registry. Ensure TOOB_REGISTRY_DIR points to your local registry directory!\n")
		errb.WriteString("Fix the C code to use these macros, or remove them from the generator.\n")
		errb.WriteString("======================================================================\n")
		return fmt.Errorf("%s", errb.String())
	}

	ui.Success("All generated macros are perfectly synchronized with the C code!")
	return nil
}
