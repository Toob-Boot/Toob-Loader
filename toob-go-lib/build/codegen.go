const generatedBanner = "/* AUTO-GENERATED BY TOOB MANIFEST COMPILER — DO NOT EDIT */"

// artifact is one fully rendered output file.
type artifact struct {
	name string
	data []byte
}

// cMacro is a name/value pair of a preprocessor definition.
type cMacro struct {
	name  string
	value string
}

var cIdentifierPattern = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func isCIdentifier(s string) bool { return cIdentifierPattern.MatchString(s) }

// hex32 formats v as a zero-padded unsigned C literal.
func hex32(v uint32) string { return fmt.Sprintf("0x%08XU", v) }

// cSource accumulates generated C/LD text and records every defined macro.
// The first invalid or duplicate macro is kept as a sticky error.
type cSource struct {
	b       strings.Builder
	guard   string
	defines []string
	seen    map[string]struct{}
	err     error
}

// newCHeader starts a header with banner and include guard.
func newCHeader(guard string) *cSource {
	s := &cSource{guard: guard}
	if !isCIdentifier(guard) {
		s.err = fmt.Errorf("header guard %q is not a valid C identifier", guard)
	}
	s.line(generatedBanner)
	s.linef("#ifndef %s", guard)
	s.linef("#define %s", guard)
	s.blank()
	return s
}

// newCFile starts a non-header output (C source, linker script) with the banner.
func newCFile() *cSource {
	s := &cSource{}
	s.line(generatedBanner)
	return s
}

func (s *cSource) line(text string) {
	s.b.WriteString(text)
	s.b.WriteByte('\n')
}

func (s *cSource) linef(format string, args ...any) {
	fmt.Fprintf(&s.b, format, args...)
	s.b.WriteByte('\n')
}

func (s *cSource) blank() { s.b.WriteByte('\n') }

func (s *cSource) define(name, value string) {
	if s.err == nil {
		s.err = s.checkNewMacro(name, value)
	}
	if s.seen == nil {
		s.seen = make(map[string]struct{})
	}
	s.seen[name] = struct{}{}
	s.defines = append(s.defines, name)
	s.linef("#define %-40s %s", name, value)
}

func (s *cSource) checkNewMacro(name, value string) error {
	if !isCSymbol(name) {
		return fmt.Errorf("generated macro name %q is not a valid C identifier", name)
	}
	if strings.ContainsAny(value, "\r\n") {
		return fmt.Errorf("generated macro %s value must not contain line breaks", name)
	}
	if strings.HasSuffix(strings.TrimRight(value, " \t"), `\`) {
		return fmt.Errorf("generated macro %s value must not end with line-continuation '\\'", name)
	}
	if _, dup := s.seen[name]; dup {
		return fmt.Errorf("generated macro %s is defined more than once; the hardware description contains "+
			"names that collide after upper-casing or prefixing", name)
	}
	return nil
}

func (s *cSource) definef(name, format string, args ...any) {
	s.define(name, fmt.Sprintf(format, args...))
}

func (s *cSource) writeBraceList(name string, items []string, audited bool) {
	if len(items) == 0 {
		if s.err == nil {
			s.err = fmt.Errorf("generated macro list %s must not be empty", name)
		}
		return
	}
	if s.err == nil {
		s.err = s.checkNewMacro(name, "{}")
	}
	for _, item := range items {
		if strings.ContainsAny(item, "\r\n") || strings.HasSuffix(strings.TrimRight(item, " \t"), `\`) {
			if s.err == nil {
				s.err = fmt.Errorf("generated macro list %s item %q contains invalid line break or trailing '\\'", name, item)
			}
			return
		}
	}
	if s.seen == nil {
		s.seen = make(map[string]struct{})
	}
	s.seen[name] = struct{}{}
	if audited {
		s.defines = append(s.defines, name)
	}
	s.linef("#define %-40s { \\", name)
	for i, item := range items {
		sep := ","
		if i == len(items)-1 {
			sep = ""
		}
		s.linef("    %s%s \\", item, sep)
	}
	s.line("}")
}

// defineList emits an audited brace-initializer macro, one item per line.
func (s *cSource) defineList(name string, items []string) {
	s.writeBraceList(name, items, true)
}

// defineLayoutHintList emits a non-audited brace-initializer macro, one item per line.
func defineLayoutHintList(s *cSource, name string, items []string) {
	s.writeBraceList(name, items, false)
}

func (s *cSource) section(title string) {
	if s.err == nil {
		s.err = validateDisplayText("section title", title)
	}
	s.line("/* ========================================================================")
	s.linef(" * %s", title)
	s.line(" * ======================================================================== */")
}

// finish closes the include guard (if any) and returns the rendered bytes.
func (s *cSource) finish() ([]byte, error) {
	if s.err != nil {
		return nil, s.err
	}
	if s.guard != "" {
		s.linef("#endif /* %s */", s.guard)
	}
	return []byte(s.b.String()), nil
}

// ParseU32Literal parses a decimal or 0x-prefixed hexadecimal uint32 literal
// with identical meaning in Go and C. Octal-looking decimals, signs, digit
// separators and binary/octal prefixes are rejected.
func ParseU32Literal(raw string) (uint32, error) { return parseU32Literal(raw) }

func parseU32Literal(raw string) (uint32, error) {
	digits, base := raw, 10
	if len(raw) > 2 && (raw[:2] == "0x" || raw[:2] == "0X") {
		digits, base = raw[2:], 16
	} else if len(raw) > 1 && raw[0] == '0' {
		return 0, fmt.Errorf("literal %q has a leading zero (C would read it as octal)", raw)
	}
	v, err := strconv.ParseUint(digits, base, 32)
	if err != nil {
		return 0, fmt.Errorf("literal %q is not a valid uint32: %w", raw, err)
	}
	return uint32(v), nil
}

// ParseU64Literal parses a decimal or 0x-prefixed hexadecimal uint64 literal
// using the same C-safe syntax rules as ParseU32Literal (MED-16).
func ParseU64Literal(raw string) (uint64, error) { return parseU64Literal(raw) }

func parseU64Literal(raw string) (uint64, error) {
	digits, base := raw, 10
	if len(raw) > 2 && (raw[:2] == "0x" || raw[:2] == "0X") {
		digits, base = raw[2:], 16
	} else if len(raw) > 1 && raw[0] == '0' {
		return 0, fmt.Errorf("literal %q has a leading zero (C would read it as octal)", raw)
	}
	v, err := strconv.ParseUint(digits, base, 64)
	if err != nil {
		return 0, fmt.Errorf("literal %q is not a valid uint64: %w", raw, err)
	}
	return v, nil
}

// cU32Literal validates raw and returns it as an unsigned C literal, preserving
// the author's notation (e.g. "0x1F" -> "0x1FU").
func cU32Literal(raw string) (string, error) {
	if _, err := parseU32Literal(raw); err != nil {
		return "", err
	}
	return raw + "U", nil
}

// cAddrLiteral validates raw as a 32-bit or 64-bit address literal, emitting
// a "U" suffix when <= 0xFFFFFFFF and "ULL" when > 0xFFFFFFFF (MED-16).
func cAddrLiteral(raw string) (string, uint64, error) {
	v, err := parseU64Literal(raw)
	if err != nil {
		return "", 0, err
	}
	if v > math.MaxUint32 {
		return raw + "ULL", v, nil
	}
	return raw + "U", v, nil
}

// cUnsigned renders a JSON/TOML scalar as an unsigned 32-bit C literal.
func cUnsigned(v any) (string, error) {
	switch val := v.(type) {
	case string:
		return cU32Literal(val)
	case float64:
		if val < 0 || val > math.MaxUint32 || val != math.Trunc(val) {
			return "", fmt.Errorf("number %v is not an integral uint32", val)
		}
		return fmt.Sprintf("%dU", uint32(val)), nil
	case int64:
		if val < 0 || val > math.MaxUint32 {
			return "", fmt.Errorf("number %d is out of uint32 range", val)
		}
		return fmt.Sprintf("%dU", val), nil
	default:
		return "", fmt.Errorf("unsupported value type %T (expected string or integer)", v)
	}
}

// writeArtifacts writes every artifact into outDir, skipping unchanged files
// so incremental builds do not recompile untouched translation units.
func writeArtifacts(outDir string, artifacts []artifact) error {
	// #nosec G301 -- generated C/LD build dir must be readable inside unprivileged toolchain containers
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	for _, a := range artifacts {
		if err := writeFileIfChanged(filepath.Join(outDir, a.name), a.data); err != nil {
			purgeGeneratedCodeArtifacts(outDir)
			return err
		}
	}
	return nil
}

func purgeGeneratedCodeArtifacts(outDir string) {
	if strings.TrimSpace(outDir) == "" {
		return
	}
	for _, name := range generatedCodeArtifacts {
		_ = os.Remove(filepath.Join(outDir, name))
	}
}

// WriteFileIfChanged writes data to path atomically only when path is missing,
// not a regular file, or has different byte contents.
func WriteFileIfChanged(path string, data []byte) error { return writeFileIfChanged(path, data) }

func writeFileIfChanged(path string, data []byte) error {
	if info, err := os.Lstat(path); err == nil && info.Mode().IsRegular() && info.Size() == int64(len(data)) {
		// #nosec G304 -- path is validated by the caller on a verified regular file
		if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
			return nil
		}
	}
	return writeFileAtomic(path, data)
}

// WriteFileAtomic replaces path through a temporary file in the same directory
// so concurrent readers or crashes never observe a truncated file.
func WriteFileAtomic(path string, data []byte) error { return writeFileAtomic(path, data) }

func writeFileAtomic(path string, data []byte) (err error) {
	tmp, err := os.CreateTemp(filepath.Dir(path), filepath.Base(path)+".tmp*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer func() {
		if err != nil {
			_ = os.Remove(tmpName)
		}
	}()
	if _, err = tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if closeErr := tmp.Close(); closeErr != nil {
		err = closeErr
		return err
	}
	// #nosec G302 -- generated headers/linker scripts must be readable by compiler processes inside Docker
	if chmodErr := os.Chmod(tmpName, 0o644); chmodErr != nil {
		err = chmodErr
		return err
	}
	for attempt := range 5 {
		err = os.Rename(tmpName, path)
		if err == nil {
			return nil
		}
		// Clear read-only attribute on existing regular target if present on Windows.
		if info, stErr := os.Lstat(path); stErr == nil && info.Mode().IsRegular() {
			// #nosec G302 -- restore writable permission before atomic replacement
			_ = os.Chmod(path, 0o644)
		}
		if attempt < 4 {
			time.Sleep(15 * time.Millisecond)
		}
	}
	return err
}

// removeStaleArtifacts deletes optional artifacts not produced by this build
// and all obsolete artifacts.
func removeStaleArtifacts(outDir string, produced []artifact) error {
	isProduced := func(name string) bool {
		for _, a := range produced {
			if a.name == name {
				return true
			}
		}
		return false
	}
	var stale []string
	for _, name := range optionalArtifacts {
		if !isProduced(name) {
			stale = append(stale, name)
		}
	}
	stale = append(stale, obsoleteArtifacts...)

	for _, name := range stale {
		if err := os.Remove(filepath.Join(outDir, name)); err != nil && !errors.Is(err, os.ErrNotExist) {
			return fmt.Errorf("failed to remove stale artifact %s: %w", name, err)
		}
	}
	return nil
}
